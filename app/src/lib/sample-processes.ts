/**
 * Отдельная копия шаблона для правки на холсте.
 *
 * Собственный id шаблона копия сохраняет: он же ключ хранилища на сервере, а
 * шаблон один и тот же. Пока id был случайным, каждое открытие страницы
 * заводило ЕЩЁ ОДНУ запись — `Home` сохраняет начальную карту на сервер, чтобы
 * работала выгрузка, — и в списке «Процессы на сервере» набралось 99 копий
 * «Выдачи кредита» с неразличимыми именами. Среди них терялись настоящие
 * карты, и сотрудник открывал старую копию вместо свежей.
 */
export function cloneSampleProcess(process: BusinessProcess): BusinessProcess {
  const newRegId = `reg-${randomUUID().slice(0, 8)}`
  const now = new Date().toISOString().split('T')[0]
  return {
    ...process,
    fileName: process.fileName,
    passport: { ...process.passport, createdDate: now, updatedDate: now },
    nodes: process.nodes.map((n) => ({ ...n })),
    edges: process.edges.map((e) => ({ ...e })),
    lanes: process.lanes.map((l) => ({ ...l })),
    registry: {
      ...process.registry,
      id: newRegId,
      records: process.registry.records.map((r) => ({ ...r, data: { ...r.data } })),
    },
    validation: [...process.validation],
    miningMetrics: { ...process.miningMetrics, deviations: [...process.miningMetrics.deviations] },
  }
}
